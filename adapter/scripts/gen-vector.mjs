// Deterministic cross-language vector consumed by test/AdapterVector.t.sol. Uses a PUBLICLY KNOWN test key (0xA11CE);
// never use it for anything but tests.
import { writeFileSync } from 'node:fs';
import { privateKeyToAccount } from 'viem/accounts';
import { keccak256, toBytes, pad, toHex } from 'viem';
import { buildBinding, signBinding, hashBinding, encodeHookData, poolIdFromKey, toJson } from '../src/binding.mjs';

export async function makeVector() {
  const account = privateKeyToAccount(pad(toHex(0xa11ce), { size: 32 }));
  const hook = '0x4444000000000000000000000000000000002880';
  const poolKey = {
    currency0: '0x0000000000000000000000000000000000001111',
    currency1: '0x0000000000000000000000000000000000002222',
    fee: 3000,
    tickSpacing: 60,
    hooks: hook,
  };
  const binding = buildBinding({
    taskId: '0x9ab3d5e1ca795d87364e8b46ee7cc2c67244d66eaf0a0c2eb3784b74c8447654',
    status: 'completed',
    evidenceHash: keccak256(toBytes('{"id":"fixture"}')),
    poolId: poolIdFromKey(poolKey),
    actor: '0x000000000000000000000000000000000000a11c',
    actions: 3,
    maxUses: 2,
    observedAt: 1790000000,
    expiry: 1790000300,
    epoch: 1,
    chainId: 46630,
    hook,
    nonce: 424242n,
  });
  const signature = await signBinding(binding, account);
  return {
    note: 'Generated by adapter/scripts/gen-vector.mjs with the public test key 0xA11CE. Do not edit by hand.',
    signer: account.address,
    poolKey,
    poolId: binding.poolId,
    binding: toJson(binding),
    digest: hashBinding(binding),
    signature,
    hookData: encodeHookData(binding, signature),
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = process.argv[2] ?? '../test/fixtures/adapter-vector.json';
  writeFileSync(out, `${JSON.stringify(await makeVector(), null, 2)}\n`);
  console.log(`wrote ${out}`);
}
